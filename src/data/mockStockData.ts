function generateHistory(basePrice: number, volatility: number = 0.015, trend: number = 0.003) {
  const points = [];
  let currentPrice = basePrice * 0.88;
  const dates = [
    '10/01', '10/02', '10/03', '10/04', '10/07', '10/08', '10/09', '10/11',
    '10/14', '10/15', '10/16', '10/17', '10/18', '10/21', '10/22', '10/23',
    '10/24', '10/25', '10/28', '10/29', '10/30', '10/31', '11/01', '11/02'
  ];

  for (let i = 0; i < dates.length; i++) {
    const isToday = i === dates.length - 1;
    const randomChange = (Math.random() - 0.48) * volatility * currentPrice;
    currentPrice = isToday ? basePrice : currentPrice * (1 + trend) + randomChange;
    const open = currentPrice * (1 + (Math.random() - 0.5) * 0.008);
    const high = Math.max(open, currentPrice) * (1 + Math.random() * 0.01);
    const low = Math.min(open, currentPrice) * (1 - Math.random() * 0.01);
    const ma5 = currentPrice * (1 - (Math.random() - 0.5) * 0.01);
    const ma20 = currentPrice * (0.97 + Math.random() * 0.02);
    const volume = Math.floor(18000 + Math.random() * 25000);

    points.push({
      date: dates[i],
      price: Number(currentPrice.toFixed(2)),
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(currentPrice.toFixed(2)),
      ma5: Number(ma5.toFixed(2)),
      ma20: Number(ma20.toFixed(2)),
      volume
    });
  }
  return points;
}

